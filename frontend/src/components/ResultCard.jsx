import React, { useState } from 'react';
import {
  ShieldCheck, ShieldAlert, ShieldX, Download, FileText,
  AlertTriangle, TrendingUp, ChevronDown, ChevronUp, Info
} from 'lucide-react';
import api from '../services/api';

export default function ResultCard({ result, applicationData }) {
  const [showBureau, setShowBureau] = useState(false);

  if (!result) return null;

  const {
    risk_score, confidence, decision, explanation,
    important_features, credit_bureau_data,
    internal_score, fraud_flags, risk_category, payslip_data,
  } = result;

  const currSymbol = applicationData?.currency === 'INR' ? '₹' : '$';

  const downloadTextReport = () => {
    const ts  = new Date().toLocaleString();
    const content = `
╔═══════════════════════════════════════════════════════════╗
║        AI LOAN UNDERWRITING — DECISION REPORT            ║
╚═══════════════════════════════════════════════════════════╝
Generated: ${ts}

─── APPLICANT ───────────────────────────────────────────────
Name:              ${applicationData?.full_name || applicationData?.user_id || 'N/A'}
Age:               ${applicationData?.age || 'N/A'}
Contact:           ${applicationData?.contact || 'N/A'}
Monthly Income:    ${currSymbol}${applicationData?.income?.toLocaleString() || 'N/A'}
Employment Type:   ${applicationData?.employment_type || 'N/A'}
Employment Length: ${applicationData?.employment_length || 'N/A'} years

─── LOAN REQUEST ────────────────────────────────────────────
Loan Amount:       ${currSymbol}${applicationData?.loan_amount?.toLocaleString() || 'N/A'}
Loan Tenure:       ${applicationData?.loan_tenure || 'N/A'} months
Purpose:           ${applicationData?.loan_purpose || 'N/A'}
Existing EMI:      ${currSymbol}${applicationData?.existing_emi?.toLocaleString() || '0'}

─── AI DECISION ─────────────────────────────────────────────
Final Decision:    ${decision?.toUpperCase()}
Risk Category:     ${risk_category || 'N/A'}
Default Risk:      ${(risk_score * 100).toFixed(1)}%
Confidence:        ${(confidence * 100).toFixed(1)}%
Internal Score:    ${internal_score || 'N/A'} (illustrative 300-900, NOT official CIBIL)

─── EXPLANATION ─────────────────────────────────────────────
${explanation}

─── KEY FACTORS (SHAP) ──────────────────────────────────────
${important_features?.map((f, i) =>
  `${i + 1}. ${f.feature.replace(/_/g, ' ').toUpperCase()}\n   ${f.impact}`
).join('\n\n') || 'Not available'}

${fraud_flags && fraud_flags.length > 0 ? `
─── ANOMALY FLAGS ───────────────────────────────────────────
${fraud_flags.map(f => `• ${f}`).join('\n')}
` : ''}
─── CREDIT BUREAU ───────────────────────────────────────────
${credit_bureau_data?.disclaimer || 'All credit data is SIMULATED for demonstration purposes.'}

─── DISCLAIMER ──────────────────────────────────────────────
This report is generated by an AI-powered underwriting system.
All decisions should be reviewed by qualified personnel.
The internal credit score is NOT an official CIBIL score.
    `;

    const blob = new Blob([content], { type: 'text/plain' });
    const url  = URL.createObjectURL(blob);
    const a    = document.createElement('a');
    a.href = url;
    a.download = `Loan_Decision_${applicationData?.user_id || 'Report'}_${Date.now()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const downloadPDFReport = async () => {
    try {
      const response = await api.post('/download-report', {
        ...applicationData,
        ...result,
        important_features: result.important_features,
      }, { responseType: 'blob' });

      const blob = new Blob([response.data], { type: 'application/pdf' });
      const url  = URL.createObjectURL(blob);
      const a    = document.createElement('a');
      a.href = url;
      a.download = `Loan_Decision_${applicationData?.user_id || 'Report'}_${decision}.pdf`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    } catch {
      alert('PDF download failed. Please try the text version.');
    }
  };

  const styles = {
    Approve: {
      glow: 'shadow-[0_0_50px_-12px_rgba(16,185,129,0.3)]',
      border: 'border-emerald-500/30',
      badgeText: 'text-emerald-400',
      icon: <ShieldCheck className="w-10 h-10 text-emerald-400" />,
    },
    Review: {
      glow: 'shadow-[0_0_50px_-12px_rgba(245,158,11,0.3)]',
      border: 'border-amber-500/30',
      badgeText: 'text-amber-400',
      icon: <ShieldAlert className="w-10 h-10 text-amber-400" />,
    },
    Reject: {
      glow: 'shadow-[0_0_50px_-12px_rgba(239,68,68,0.3)]',
      border: 'border-red-500/30',
      badgeText: 'text-red-400',
      icon: <ShieldX className="w-10 h-10 text-red-400" />,
    },
  };
  const s = styles[decision] || styles.Review;

  return (
    <div className={`backdrop-blur-xl bg-white/5 rounded-3xl border ${s.border} ${s.glow} p-8 flex flex-col gap-8 animate-in fade-in zoom-in-95`}>

      {/* ── Header ── */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-6 border-b border-white/10 pb-6">
        <div className="flex items-center gap-5">
          <div className={`p-4 rounded-2xl bg-slate-950 border ${s.border} shadow-inner`}>
            {s.icon}
          </div>
          <div>
            <p className="text-xs text-slate-400 uppercase tracking-widest mb-1">Final Decision</p>
            <h1 className={`text-4xl font-black uppercase tracking-tight ${s.badgeText}`}>
              {decision}
            </h1>
            {risk_category && (
              <span className={`text-xs font-bold px-2 py-0.5 rounded-full border mt-1 inline-block ${
                risk_category === 'Low'
                  ? 'text-emerald-400 border-emerald-500/30 bg-emerald-500/10'
                  : risk_category === 'Medium'
                  ? 'text-amber-400 border-amber-500/30 bg-amber-500/10'
                  : 'text-red-400 border-red-500/30 bg-red-500/10'
              }`}>
                {risk_category} Risk
              </span>
            )}
          </div>
        </div>

        {/* Metrics + downloads */}
        <div className="flex flex-col gap-3">
          <div className="flex gap-3">
            <div className="bg-slate-900/80 px-5 py-4 rounded-2xl border border-white/5 text-center">
              <p className="text-xs text-slate-500 uppercase tracking-widest font-bold mb-1">Default Risk</p>
              <p className="text-3xl font-black text-white">
                {(risk_score * 100).toFixed(1)}<span className="text-base text-slate-500">%</span>
              </p>
            </div>
            <div className="bg-slate-900/80 px-5 py-4 rounded-2xl border border-white/5 text-center">
              <p className="text-xs text-slate-500 uppercase tracking-widest font-bold mb-1">Confidence</p>
              <p className="text-3xl font-black text-white">
                {(confidence * 100).toFixed(1)}<span className="text-base text-slate-500">%</span>
              </p>
            </div>
            {internal_score && (
              <div className="bg-slate-900/80 px-5 py-4 rounded-2xl border border-white/5 text-center">
                <p className="text-xs text-slate-500 uppercase tracking-widest font-bold mb-1">Score</p>
                <p className={`text-3xl font-black ${
                  internal_score >= 750 ? 'text-emerald-400'
                  : internal_score >= 600 ? 'text-amber-400'
                  : 'text-red-400'
                }`}>{internal_score}</p>
              </div>
            )}
          </div>
          {internal_score && (
            <p className="text-xs text-slate-600 text-center">
              Internal score: illustrative 300–900 scale. NOT an official CIBIL score.
            </p>
          )}
          <div className="flex flex-col gap-2">
            <button
              onClick={downloadPDFReport}
              className="bg-gradient-to-r from-blue-500 to-blue-600 hover:from-blue-400 hover:to-blue-500 text-white font-bold py-3 px-6 rounded-xl flex items-center justify-center gap-2 shadow-lg shadow-blue-500/25 transition-all hover:scale-105 uppercase tracking-wider text-sm"
            >
              <FileText className="w-4 h-4" /> Download PDF
            </button>
            <button
              onClick={downloadTextReport}
              className="bg-gradient-to-r from-slate-600 to-slate-700 hover:from-slate-500 hover:to-slate-600 text-white font-semibold py-2 px-6 rounded-xl flex items-center justify-center gap-2 shadow-lg transition-all hover:scale-105 uppercase tracking-wider text-xs"
            >
              <Download className="w-3.5 h-3.5" /> Text Version
            </button>
          </div>
        </div>
      </div>

      {/* ── Explanation ── */}
      <div className="bg-slate-900/40 rounded-2xl p-6 border border-white/5 relative overflow-hidden">
        <div className="absolute top-0 left-0 w-1 h-full bg-gradient-to-b from-amber-400 to-transparent opacity-50" />
        <h3 className="text-xs font-bold text-amber-500 mb-3 uppercase tracking-widest flex items-center gap-2">
          <span className="w-1.5 h-1.5 bg-amber-500 rounded-full animate-pulse" />
          AI Analysis
        </h3>
        <p className="text-slate-300 leading-relaxed text-base font-light">{explanation}</p>
      </div>

      {/* ── Payslip extracted data ── */}
      {payslip_data && (payslip_data.extracted_income || payslip_data.extracted_employer) && (
        <div className="bg-emerald-500/5 border border-emerald-500/20 rounded-2xl p-5">
          <h3 className="text-xs font-bold text-emerald-400 mb-3 uppercase tracking-widest">
            Payslip Extracted Data
          </h3>
          <div className="grid grid-cols-2 sm:grid-cols-3 gap-3">
            {[
              ['Extracted Income',   payslip_data.extracted_income ? `${currSymbol}${payslip_data.extracted_income.toLocaleString()}` : null],
              ['Employer',           payslip_data.extracted_employer],
              ['Salary Period',      payslip_data.salary_period],
              ['Employee Name',      payslip_data.employee_name],
            ].filter(([, v]) => v).map(([k, v]) => (
              <div key={k} className="bg-slate-900/50 rounded-xl px-3 py-2">
                <p className="text-slate-500 text-xs uppercase tracking-wider mb-0.5">{k}</p>
                <p className="text-white text-sm font-semibold">{v}</p>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* ── Fraud flags ── */}
      {fraud_flags && fraud_flags.length > 0 && (
        <div className="bg-amber-500/5 border border-amber-500/20 rounded-2xl p-5">
          <h3 className="text-xs font-bold text-amber-400 mb-3 uppercase tracking-widest flex items-center gap-2">
            <AlertTriangle className="w-3.5 h-3.5" /> Anomaly Signals
          </h3>
          <ul className="space-y-1.5">
            {fraud_flags.map((f, i) => (
              <li key={i} className="flex items-start gap-2 text-sm text-amber-200/80">
                <span className="text-amber-400 mt-0.5 shrink-0">•</span> {f}
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* ── SHAP Feature Analysis ── */}
      {important_features && important_features.length > 0 && (
        <div>
          <h3 className="text-xs font-bold text-slate-500 mb-4 uppercase tracking-widest">
            SHAP Feature Analysis
          </h3>
          <ul className="grid grid-cols-1 md:grid-cols-2 gap-3">
            {important_features.map((feature, idx) => (
              <li
                key={idx}
                className="bg-slate-900/60 border border-white/5 rounded-xl p-4 flex flex-col gap-1.5 hover:border-amber-500/30 hover:bg-slate-900 transition-all cursor-default group"
              >
                <span className="text-[10px] font-bold text-slate-500 uppercase tracking-widest group-hover:text-slate-400 transition-colors">
                  {feature.feature.replace(/_/g, ' ')}
                </span>
                <span className={`text-sm font-medium leading-tight ${
                  feature.impact?.toLowerCase().includes('positive') || feature.impact?.toLowerCase().includes('reducing')
                    ? 'text-emerald-400'
                    : feature.impact?.toLowerCase().includes('negative') || feature.impact?.toLowerCase().includes('increasing')
                    ? 'text-red-400'
                    : 'text-slate-300'
                }`}>
                  {feature.impact}
                </span>
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* ── Credit Bureau Data (collapsible) ── */}
      {credit_bureau_data && (
        <div className="border border-white/10 rounded-2xl overflow-hidden">
          <button
            onClick={() => setShowBureau(b => !b)}
            className="w-full flex items-center justify-between px-5 py-4 bg-slate-900/40 hover:bg-slate-900/60 transition-colors"
          >
            <div className="flex items-center gap-2">
              <TrendingUp className="w-4 h-4 text-slate-400" />
              <span className="text-sm font-bold text-slate-300">Credit Bureau Data</span>
              <span className="text-xs text-amber-400/80 bg-amber-400/10 border border-amber-400/20 px-2 py-0.5 rounded-full font-semibold">
                SIMULATED
              </span>
            </div>
            {showBureau ? <ChevronUp className="w-4 h-4 text-slate-500" /> : <ChevronDown className="w-4 h-4 text-slate-500" />}
          </button>

          {showBureau && (
            <div className="p-5 space-y-4">
              {/* Disclaimer */}
              {credit_bureau_data.disclaimer && (
                <div className="flex items-start gap-2 bg-amber-500/5 border border-amber-500/20 rounded-xl p-3">
                  <Info className="w-4 h-4 text-amber-400 shrink-0 mt-0.5" />
                  <p className="text-amber-300/80 text-xs">{credit_bureau_data.disclaimer}</p>
                </div>
              )}

              <div className="grid grid-cols-2 sm:grid-cols-3 gap-3">
                {[
                  ['Bureau',         credit_bureau_data.bureau_name],
                  ['Score',          `${credit_bureau_data.credit_score} (illustrative)`],
                  ['History',        credit_bureau_data.credit_history_years ? `${credit_bureau_data.credit_history_years} yrs` : null],
                  ['Utilization',    credit_bureau_data.credit_utilization_pct ? `${credit_bureau_data.credit_utilization_pct}%` : null],
                  ['Late Payments',  credit_bureau_data.late_payments],
                  ['90-Day Late',    credit_bureau_data.late_90_days],
                  ['Outstanding Debt', credit_bureau_data.outstanding_debt != null ? `${currSymbol}${Number(credit_bureau_data.outstanding_debt).toLocaleString()}` : null],
                  ['Previous Loans', credit_bureau_data.previous_loans],
                ].filter(([, v]) => v != null).map(([k, v]) => (
                  <div key={k} className="bg-slate-900/60 rounded-xl px-3 py-2">
                    <p className="text-slate-500 text-xs uppercase tracking-wider mb-0.5">{k}</p>
                    <p className="text-white text-sm font-semibold">{v}</p>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
